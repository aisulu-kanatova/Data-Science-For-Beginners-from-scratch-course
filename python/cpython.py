"""Answers to the questions about CPython and PyPy."""

#
# Что такое CPython и чем он отличается от Python?
# CPython - это стандартная и наиболее широко используемая реализация
# языка программирования Python.
# Разница:
# исполнение:
# Python - концепция,которая требует реализации
# CPython- программа, которая компилирует код в байт-код и исполняет его.
# Язык реализации:
# Python не зависит от языка реализации
# CPython реализован на языке С
#
# Сколько существует реализаций Python и какая из них самая популярная?
# 6 реализаций
# CPython самая популярная
#
# На каком языке написан CPython?
# на языке C
#
# Почему Python считается быстрым, несмотря на то что
# это интерпретируемый язык?
#
# Потому что код на языке С заранее компилируется в машинный код.
# Встроенные функции Python написаны на C, поэтому при их вызове работа
#  выполняется сразу в машинном коде, быстро.
#
# Укажите путь к интерпретатору CPython на вашем компьютере.
# Меню пуск --- пишем Python (выходит например Python 3.12(64-bit))
# --- правой кнопкой мыши --- open file location --
# копируем путь из адресной строки и дописываем \python.exe.
#
# Что содержится в папке include в CPython?
# заголовочные файлы с расширением .h
#
# Где найти исходный код CPython? Дайте ссылку на репозиторий GitHub.
# находится на GitHub в официальном репозитории python/cpython на GitHub
# https://github.com/python/cpython
#
# Какая команда используется для запуска файла с помощью CPython?
# Win+R → пишем cmd → открывается консоль → в ней пишем команду
# python имя_файла.py (или полный путь к python.exe и полный путь к файлу).
#
# Можно ли запускать текстовые файлы через интерпретатор Python? Почему?
# Да потому что ему без разницы какое расширение файла
#
# Как указать путь к интерпретатору и к файлу для выполнения кода?
# К интерпретатору:
# открыть папку Python → скопировать путь из адресной строки
#  Проводника → дописать \python.exe».
# К файлу:
# создаем файл -- правой кнопкой мыши --- copy as path ---
# вставляем в "путь"
#
# Чем PyPy отличается от CPython?
# у PyPy есть встроенный JIT ( Just In Time) компилятор,а CPython
#  только интерпретирует байт-код.
#
# Почему PyPy подходит не для всех проектов на Python?
# 1) PyPy обычно отстаёт от актуальной версии Python на 1-2 версии.
# 2) Он плохо пока совмещается с библиотеками на С(Pandas,NumPy).
#  С PyPy они работают с ошибками,медленнее, или не работают совсем.
#
# Где можно скачать PyPy?
# на сайте https://pypy.org
#
# Как установить PyPy после скачивания?
# Скачиваем архив .zip-- правой кнопкой мыши нажимаем -- extract all
#
# Как запустить файл с помощью PyPy?
# нажимаем win+R там пишем cmd нажимаем enter--
# туда мы будем вставлять адрес интерпретатора
#  (заходим в папку PyPy -- копируем путь адресной строки дописывая \pypy.exe)
#   пробел вставлять адрес файла (нажимаем правой кнопкой мыши -- copy as path),
#    запускаем
#
# Почему PyPy выполняет код быстрее, чем CPython?
# PyPy вместо того чтобы заново переводить повторяющиеся участки кода
# компилирует их в машинный код. Его процессор выполняет напрямую код,
#  поэтому Pypy выполняет код быстрее.

